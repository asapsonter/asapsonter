import { copyFileSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { defineConfig, loadEnv } from 'vite'
import type { Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import { isPublishable, parsePost, sortByDateDesc } from './src/lib/frontmatter'

const POSTS_DIR = 'src/posts'

const xml = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

// Apache config for cPanel hosts (Truehost): serve real files, send every other
// path (e.g. /blog/my-post) to index.html so the React router can handle it.
const HTACCESS = `# Generated by vite.config.ts — do not edit in dist-truehost/
Options -MultiViews
DirectoryIndex index.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # Uncomment once SSL (AutoSSL / Let's Encrypt) is active in cPanel:
  # RewriteCond %{HTTPS} off
  # RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]

  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]
  RewriteRule ^ index.html [L]
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml application/rss+xml application/xml
</IfModule>

<IfModule mod_headers.c>
  # Hashed build assets never change; cache them for a year.
  <FilesMatch "\\.(js|css|woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(html|xml)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`

/**
 * Build-time extras:
 *  - rss.xml from the Markdown posts
 *  - GitHub Pages: 404.html (copy of index.html) so deep links load the SPA
 *  - Truehost (Apache): .htaccess doing the same job
 */
function blogBuild(SITE_URL: string, target: 'github' | 'truehost'): Plugin {
  return {
    name: 'blog-build',
    apply: 'build',
    generateBundle() {
      const posts = sortByDateDesc(
        readdirSync(POSTS_DIR)
          .filter((f) => f.endsWith('.md') && isPublishable(f))
          .map((f) => parsePost(f, readFileSync(join(POSTS_DIR, f), 'utf8')))
          .filter((p) => !p.draft),
      )
      const items = posts
        .map((p) => {
          const link = `${SITE_URL}/blog/${p.slug}`
          return `    <item>
      <title>${xml(p.title)}</title>
      <link>${link}</link>
      <guid isPermaLink="true">${link}</guid>
      <pubDate>${new Date(`${p.date}T00:00:00Z`).toUTCString()}</pubDate>
      <description>${xml(p.summary)}</description>
${p.tags.map((t) => `      <category>${xml(t)}</category>`).join('\n')}
    </item>`
        })
        .join('\n')

      this.emitFile({
        type: 'asset',
        fileName: 'rss.xml',
        source: `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Sam Sonter — Blog</title>
    <link>${SITE_URL}/blog</link>
    <description>Notes on new technologies — IoT, applied ML/AI and system integration.</description>
    <language>en</language>
    <atom:link href="${SITE_URL}/rss.xml" rel="self" type="application/rss+xml" />
${items}
  </channel>
</rss>
`,
      })
    },
    writeBundle(options) {
      const dir = options.dir ?? 'dist'
      if (target === 'truehost') writeFileSync(join(dir, '.htaccess'), HTACCESS)
      else copyFileSync(join(dir, 'index.html'), join(dir, '404.html'))
    },
  }
}

// `npm run build` -> GitHub Pages (.env); `npm run build:truehost` -> Truehost (.env.truehost)
export default defineConfig(({ mode, command }) => {
  const env = loadEnv(mode, process.cwd(), 'VITE_')
  const target = mode === 'truehost' ? 'truehost' : 'github'
  const siteUrl = env.VITE_SITE_URL.replace(/\/$/, '')

  if (command === 'build' && target === 'truehost' && siteUrl.includes('YOUR-DOMAIN')) {
    throw new Error('Set VITE_SITE_URL in .env.truehost to your real domain before running build:truehost.')
  }

  return {
    base: env.VITE_BASE || '/',
    plugins: [react(), tailwindcss(), blogBuild(siteUrl, target)],
    build: { outDir: target === 'truehost' ? 'dist-truehost' : 'dist', emptyOutDir: true },
    resolve: {
      alias: {
        '@': '/src',
      },
    },
  }
})
